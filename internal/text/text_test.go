func TestD取随机字符(t *testing.T) {
	空 := 取随机字符(0, true, true, true)
	dlog.Info("取随机字符", "位数", 0, "结果", 空, "期望", "")
	if 空 != "" {
		t.Errorf("位数0应为空")
	}

	默认 := 取随机字符(16, false, false, false)
	dlog.Info("取随机字符默认", "位数", 16, "结果", 默认, "期望长度", 16)
	if len(默认) != 16 {
		t.Errorf("默认长度不符")
	}
	for _, 字 := range 默认 {
		ok := (字 >= 'a' && 字 <= 'z') || (字 >= '0' && 字 <= '9')
		if !ok {
			t.Errorf("默认字符集外字符: %q", 字)
		}
	}

	仅数字 := 取随机字符(8, false, false, true)
	dlog.Info("取随机字符仅数字", "位数", 8, "结果", 仅数字, "期望长度", 8)
	if len(仅数字) != 8 {
		t.Errorf("仅数字长度不符")
	}
	for _, 字 := range 仅数字 {
		if 字 < '0' || 字 > '9' {
			t.Errorf("仅数字出现非法字符: %q", 字)
		}
	}

	全开 := 取随机字符(32, true, true, true)
	dlog.Info("取随机字符全开", "位数", 32, "结果", 全开, "期望长度", 32)
	if len(全开) != 32 {
		t.Errorf("全开长度不符")
	}
	for _, 字 := range 全开 {
		if !strings.ContainsRune(字符集小写+字符集大写+字符集数字, 字) {
			t.Errorf("全开字符集外字符: %q", 字)
		}
	}
}
